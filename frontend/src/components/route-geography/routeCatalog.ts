export function routeCorridor(
  originZip: string,
  destinationZip: string,
  origin: RoutePoint,
  destination: RoutePoint,
): RouteCorridor {
  const points = ROAD_ROUTES[`${originZip}:${destinationZip}`];
  return points
    ? {
        points: [origin, ...points.slice(1, -1), destination],
        label: "Bundled road route",
        isRoadRoute: true,
      }
    : { points: [origin, destination], label: "Endpoint geography only", isRoadRoute: false };
}
